import {
  Bar,
  BarChart,
  CartesianGrid,
  Cell,
  Line,
  LineChart,
  Pie,
  PieChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts';
import { BarChart3, PieChart as PieIcon, TrendingUp } from 'lucide-react';
import { format } from 'date-fns';
import ChartCard from '../common/ChartCard';
import { REPORT_TYPE_COLORS, REPORT_TYPES } from '../../data/reports';
import { dedupeBy } from '../../utils/formatters';

const REGION_COLORS = ['#08764F', '#16845C', '#0EA5A4', '#F59E0B', '#8A94A6', '#269B5B', '#3B6FC4'];

const tooltipStyle = {
  borderRadius: 8,
  border: '1px solid #DCE7E5',
  fontSize: 11,
  boxShadow: '0 6px 18px rgba(16,45,61,.1)',
};

export default function ReportsAnalytics({ reports }) {
  const byType = REPORT_TYPES.map((type) => ({
    type,
    count: reports.filter((report) => report.type === type).length,
    color: REPORT_TYPE_COLORS[type],
  }));

  const regionNames = dedupeBy(reports, (report) => report.regionName).map((report) => report.regionName);
  const byRegion = regionNames.map((regionName, index) => ({
    name: regionName,
    value: reports.filter((report) => report.regionName === regionName).length,
    color: REGION_COLORS[index % REGION_COLORS.length],
  }));

  const timeMap = new Map();
  reports.forEach((report) => {
    const key = format(new Date(report.generatedAt), 'MMM yyyy');
    timeMap.set(key, (timeMap.get(key) || 0) + 1);
  });
  const overTime = [...timeMap.entries()]
    .map(([month, count]) => ({ month, count, sortKey: new Date(`01 ${month}`).getTime() }))
    .sort((a, b) => a.sortKey - b.sortKey);

  return (
    <div className="analytics-grid">
      <ChartCard
        title="Reports by Type"
        subtitle="Distribution across report categories"
        icon={BarChart3}
      >
        <div className="chart-card-body tall" style={{ paddingTop: 18 }}>
          <ResponsiveContainer width="100%" height="100%">
            <BarChart data={byType} margin={{ top: 4, right: 12, left: -18, bottom: 0 }}>
              <CartesianGrid strokeDasharray="3 4" vertical={false} stroke="#E9F0EE" />
              <XAxis
                dataKey="type"
                tickLine={false}
                axisLine={false}
                tick={{ fontSize: 9, fill: '#7C8B96' }}
                interval={0}
              />
              <YAxis allowDecimals={false} tickLine={false} axisLine={false} tick={{ fontSize: 9.5, fill: '#8A98A3' }} />
              <Tooltip cursor={{ fill: 'rgba(234,247,241,0.65)' }} contentStyle={tooltipStyle} />
              <Bar dataKey="count" radius={[4, 4, 0, 0]} isAnimationActive={false} maxBarSize={30}>
                {byType.map((entry) => (
                  <Cell key={entry.type} fill={entry.color} />
                ))}
              </Bar>
            </BarChart>
          </ResponsiveContainer>
        </div>
      </ChartCard>

      <ChartCard title="Region Coverage" subtitle="Reports generated by study region" icon={PieIcon}>
        <div className="chart-card-body tall" style={{ paddingTop: 8 }}>
          <ResponsiveContainer width="100%" height="100%">
            <PieChart>
              <Pie
                data={byRegion}
                dataKey="value"
                nameKey="name"
                innerRadius={44}
                outerRadius={70}
                paddingAngle={2}
                stroke="#fff"
                strokeWidth={2}
                isAnimationActive={false}
              >
                {byRegion.map((entry) => (
                  <Cell key={entry.name} fill={entry.color} />
                ))}
              </Pie>
              <Tooltip contentStyle={tooltipStyle} />
            </PieChart>
          </ResponsiveContainer>
        </div>
        <div style={{ padding: '0 14px 12px', display: 'flex', flexWrap: 'wrap', gap: '5px 12px' }}>
          {byRegion.map((entry) => (
            <span key={entry.name} className="legend-row" style={{ fontSize: 9.5 }}>
              <span className="legend-swatch" style={{ background: entry.color }} aria-hidden="true" />
              {entry.name.replace(' Forest Landscape', '').replace(' Forest Range', '')} ({entry.value})
            </span>
          ))}
        </div>
      </ChartCard>

      <ChartCard title="Reports Generated Over Time" subtitle="Monthly generation activity" icon={TrendingUp}>
        <div className="chart-card-body tall" style={{ paddingTop: 18 }}>
          <ResponsiveContainer width="100%" height="100%">
            <LineChart data={overTime} margin={{ top: 4, right: 16, left: -18, bottom: 0 }}>
              <CartesianGrid strokeDasharray="3 4" vertical={false} stroke="#E9F0EE" />
              <XAxis
                dataKey="month"
                tickLine={false}
                axisLine={false}
                tick={{ fontSize: 9.5, fill: '#7C8B96' }}
                interval="preserveStartEnd"
              />
              <YAxis allowDecimals={false} tickLine={false} axisLine={false} tick={{ fontSize: 9.5, fill: '#8A98A3' }} />
              <Tooltip contentStyle={tooltipStyle} />
              <Line
                type="monotone"
                dataKey="count"
                stroke="#16845C"
                strokeWidth={2.2}
                dot={{ r: 3, fill: '#fff', stroke: '#08764F', strokeWidth: 2 }}
                activeDot={{ r: 4.5 }}
                isAnimationActive={false}
              />
            </LineChart>
          </ResponsiveContainer>
        </div>
      </ChartCard>
    </div>
  );
}
