import { SAMPLE_ANALYSIS_RUNS } from '../data/analysisRuns';
import { REGION_SUMMARIES } from '../data/studyAreas';
import { readJson, STORAGE_KEYS, writeJson } from '../utils/storage';

function clamp(value, min, max) {
  return Math.min(max, Math.max(min, value));
}

function round(value, digits = 1) {
  const factor = 10 ** digits;
  return Math.round(value * factor) / factor;
}

export function getAnalysisRuns() {
  return readJson(STORAGE_KEYS.analysisRuns, SAMPLE_ANALYSIS_RUNS);
}

export function getGeneratedResults() {
  return readJson(STORAGE_KEYS.generatedResults, []);
}

export function createDemoRunOutput({
  region,
  startDate,
  endDate,
  compositingWindow,
  algorithm,
  confidenceThreshold,
}) {
  const runId = `run-${Date.now().toString().slice(-7)}`;
  const base = region.areaKm2;
  const now = new Date().toISOString();
  const threshold = Number(confidenceThreshold);

  const templates = [
    {
      suffix: 'North Block',
      classification: 'Likely Forest Loss',
      areaFactor: 0.011,
      confidence: clamp(threshold + 0.1, 0.78, 0.97),
      status: 'Needs Review',
      latOffset: 0.022,
      lngOffset: 0.018,
    },
    {
      suffix: 'Central Ridge',
      classification: 'Possible Forest Loss',
      areaFactor: 0.0075,
      confidence: clamp(threshold - 0.02, 0.61, 0.9),
      status: 'Review',
      latOffset: -0.014,
      lngOffset: 0.024,
    },
    {
      suffix: 'River Corridor',
      classification: 'No Detected Loss',
      areaFactor: 0.004,
      confidence: clamp(threshold + 0.14, 0.8, 0.98),
      status: 'Clear',
      latOffset: 0.006,
      lngOffset: -0.021,
    },
    {
      suffix: 'South Edge',
      classification: 'Insufficient Evidence',
      areaFactor: 0.0028,
      confidence: clamp(0.5 + threshold * 0.12, 0.45, 0.68),
      status: 'Needs Review',
      latOffset: -0.024,
      lngOffset: -0.01,
    },
  ];

  const results = templates.map((template, index) => ({
    id: `${runId}-res-${index + 1}`,
    runId,
    location: `${region.name} — ${template.suffix}`,
    district: region.district,
    state: region.state,
    regionId: region.id,
    regionName: region.name,
    classification: template.classification,
    areaKm2: round(base * template.areaFactor, 1),
    confidence: round(template.confidence, 2),
    observationDate: endDate,
    status: template.status,
    coordinates: [round(region.center[0] + template.latOffset, 5), round(region.center[1] + template.lngOffset, 5)],
    summary:
      'Generated by the simulated demo workflow. This is not a real satellite-data result and must be replaced by backend output.',
    isDemo: true,
    generated: true,
  }));

  const sum = (classification) =>
    round(
      results
        .filter((result) => result.classification === classification)
        .reduce((total, result) => total + result.areaKm2, 0),
      1,
    );

  const likely = sum('Likely Forest Loss');
  const possible = sum('Possible Forest Loss');
  const insufficient = sum('Insufficient Evidence');
  const noLoss = round(base - likely - possible - insufficient, 1);

  const summary = {
    total: base,
    likely,
    possible,
    noLoss,
    insufficient,
    observationDate: endDate,
    window: `${startDate} – ${endDate}`,
    generatedAt: now,
  };

  const run = {
    id: runId,
    regionId: region.id,
    regionName: region.name,
    state: region.state,
    district: region.district,
    startDate,
    endDate,
    compositingWindow,
    algorithm,
    confidenceThreshold: threshold,
    status: 'Completed',
    findings: results.length,
    classification: 'Likely Forest Loss',
    createdAt: now,
    isDemo: true,
    simulated: true,
    summary,
  };

  return { run, results, summary };
}

export function persistDemoRun(run, results) {
  const nextRuns = [run, ...getAnalysisRuns()];
  const nextResults = [...results, ...getGeneratedResults()];
  writeJson(STORAGE_KEYS.analysisRuns, nextRuns);
  writeJson(STORAGE_KEYS.generatedResults, nextResults);
  return { runs: nextRuns, results: nextResults };
}

// Real runs are stored apart from the demo seed list on purpose: the seeded runs
// carry invented confidences, and a page that shows both must know which is which.
export function getRealRuns() {
  return readJson(STORAGE_KEYS.realRuns, []);
}

export function persistRealRun(run) {
  const next = [run, ...getRealRuns()].slice(0, 5);
  writeJson(STORAGE_KEYS.realRuns, next);
  return next;
}

export function getDemoSummaryForRegion(region) {
  if (!region) return null;
  const summary = REGION_SUMMARIES[region.state];
  if (!summary) return null;
  return { ...summary, total: region.areaKm2 };
}
